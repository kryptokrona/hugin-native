export async function saveMessage(
  conversation: string,
  message: string,
  reply: string,
  timestamp: number,
  hash: string,
  sent: boolean,
  myaddress: string,
  tip: TipType | false = false,
  nickname: string | undefined,
  status: MessageStatus = 'success'
) {

  // A received DM is saved once: not again under its message id, and not when the conversation
  // already has a received DM with this timestamp (stored under another hash). An own message
  // saved again under its hash replaces its row (its status changes); another own message with
  // this conversation and timestamp is not saved.
  if (await messageExists(hash)) {
    if (!sent) return;
  } else if (await dmAt(conversation, timestamp, sent)) {
    return;
  }

  console.log('Saving message: ', message);
  if ((!message || message?.length === 0) && !tip) {
    return false;
  }
  try {
    await db.executeSql(
      'REPLACE INTO messages (conversation, message, reply, timestamp, hash, sent, read, status, tip) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)',
      [
        conversation,
        message,
        reply,
        timestamp,
        hash,
        sent ? 1 : 0,
        sent ? 1 : 0,
        status,
        JSON.stringify(tip),
      ],
    );

    if (!sent) {
      const contact = await getContact(conversation);
      nickname = contact.name;
    }

    const newMessage: Message = {
      address: sent ? myaddress : conversation,
      hash: hash,
      message: message,
      nickname: nickname || 'Anon',
      reactions: [],
      reply: reply,
      room: conversation,
      sent: sent,
      timestamp: timestamp,
      status: status,
      tip,
    };
    return newMessage;
  } catch (err) {
    console.log('savemsgerror:', err);
    return false;
  }
}

