export const toMessage = (res: any) => {
  const message: Message & { signature?: string } = {
    address: res.address,

    file: res.file,

    //Hash identifier of the message
    hash: res.hash,

    //Message
    message: res.message,

    //Nickname
    nickname: res.nickname,

    // Emoji's on this message
    reactions: res.reactions ? res.reactions : [],

    //All the replies to this message
    replies: res?.replies,

    //The reply hash of the message
    reply: res.reply,

    //The original message this is a reply to
    replyto: res?.replyto,

    //The room the message is in
    room: res.room,

    //If sent or not
    sent: res.sent,

    //Timestmap
    timestamp: res.timestamp,

    tip: res.tip,

    status: res.status,

    read: res.read === 1,

    //The author's signature (room and feed messages; '' for rows without one)
    signature: typeof res.signature === 'string' ? res.signature : '',
  };

  return message;
};
