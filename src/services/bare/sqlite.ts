export async function addContact(
  name: string,
  address: string,
  messagekey: string,
  add: boolean = false,
) {
  return new Promise<any>((resolve) => {
    let returnVal: any;

    db.transaction(
      tx => {
        tx.executeSql(
          'SELECT * FROM contacts WHERE address = ?',
          [address],
          (tx, results) => {
            if (results.rows.length > 0) {
              // A row with an empty name (written by earlier versions of the
              // app, which stored handshake state in contacts before the
              // contact was added) is promoted to a contact row instead of
              // bailing, so that Beam.new runs and the name is set. Callers
              // get a truthy value back and continue as for a new contact.
              const existing = results.rows.item(0);
              if (existing && (!existing.name || existing.name === '')) {
                const timestamp = Date.now();
                tx.executeSql(
                  'UPDATE contacts SET name = ?, latestmessage = ? WHERE address = ?',
                  [name, timestamp, address],
                );
                console.log('[sqlite.ts] Promoted KEM seed row to contact:', address);
                returnVal = { address, messagekey: existing.messagekey, name };
                return;
              }
              console.log('[sqlite.ts] Contact already exists:', name);
              returnVal = false;
              return;
            }

            const timestamp = Date.now();
            tx.executeSql(
              'INSERT INTO contacts (name, address, messagekey, latestmessage) VALUES (?, ?, ?, ?)',
              [name, address, messagekey, timestamp],
              (tx, insertResult) => {
                console.log('Added contact: ', address, messagekey, name);
                returnVal = { address, messagekey, name };

                if (add) {
                  const hash = timestamp.toString();
                  const message = 'Conversation started';
                  const reply = '';
                  const sent = true;
                  const tip = false;

                  tx.executeSql(
                    'SELECT * FROM messages WHERE timestamp = ?',
                    [timestamp],
                    (tx, msgExistsResult) => {
                      if (msgExistsResult.rows.length === 0) {
                        tx.executeSql(
                          'REPLACE INTO messages (conversation, message, reply, timestamp, hash, sent, read, status, tip) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)',
                          [
                            address,
                            message,
                            reply,
                            timestamp,
                            hash,
                            sent ? 1 : 0,
                            sent ? 1 : 0,
                            'success',
                            JSON.stringify(tip),
                          ]
                        );
                      }
                    }
                  );
                }
              }
            );
          }
        );
      },
      error => {
        console.log('Failed to add contact: ', error);
        resolve(undefined);
      },
      () => {
        resolve(returnVal);
      }
    );
  });
}

