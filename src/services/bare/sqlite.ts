export async function getMessages(
  conversation: string,
  page: number,
  history = true,
) {
  const limit: number = 55;
  const offset: number = pageOffset(page, limit);
  const { name, address } = useUserStore.getState().user;

  // Mark pending messages older than 30 seconds as failed
  const thirtySecondsAgo = Date.now() - 30000;
  try {
    await db.executeSql(
      `UPDATE messages SET status = 'failed' WHERE status = 'pending' AND timestamp < ?`,
      [thirtySecondsAgo]
    );
  } catch (err) {
    console.log('Failed to update old pending messages', err);
  }

  const results: [ResultSet] = await db.executeSql(
    'SELECT * FROM messages WHERE conversation = ? ORDER BY timestamp DESC LIMIT ? OFFSET ?',
    [conversation, limit, offset],
  );
  const found: any[] = [];
  for (const result of results) {
    for (let index = 0; index < result.rows.length; index++) {
      const res = result.rows.item(index);
      if (res !== undefined) {
        found.push(res);
      }
    }
  }
  const rows = oneRowPerMessage(found);

  if (history) {
    const files = Files.all();
    const messages = [];
    for (const res of rows) {
      const file = files.find((a) => a.hash === res.hash);

      if (file) {
        res.file = file;
      }
      res.room = res.conversation;
      res.address = res.sent ? address : res.conversation;
      const contact = await getContact(res.address);
      res.nickname = res.sent ? name : contact.name;
      const r: Message = toMessage(res);
      messages.push(r);
    }

    return messages.reverse();
  }

  const rowSet: any = { rows: { length: rows.length, item: (i: number) => rows[i] } };
  return await setReplies([rowSet]);
}

async function setReplies(results: [ResultSet]) {
  const messages: Message[] = [];
  const files = Files.all();
  
  const baseMessages: any[] = [];
  for (const result of results) {
    for (let index = 0; index < result.rows.length; index++) {
      const res = result.rows.item(index);
      if (res !== undefined) {
        baseMessages.push(res);
      }
    }
  }

  if (baseMessages.length === 0) {
    return [];
  }

  const hashes = baseMessages.map((m: any) => m.hash);
  const replyHashesMap = new Map();
  baseMessages.forEach((m: any) => {
      if (m.reply && m.reply !== '') {
          replyHashesMap.set(m.reply, true);
      }
  });
  const replyHashes = Array.from(replyHashesMap.keys());

  const replyToMessagesMap = new Map();
  if (replyHashes.length > 0) {
      const placeholders = replyHashes.map(() => '?').join(',');
      const replyResults = await db.executeSql(
          `SELECT * FROM roomsmessages WHERE hash IN (${placeholders}) ORDER BY timestamp ASC`,
          replyHashes
      );
      
      for (const result of replyResults) {
          for (let index = 0; index < result.rows.length; index++) {
              const r = result.rows.item(index);
              if (r !== undefined) {
                   const file = files.find((a: FileInfo) => a.hash === r.hash);
                   if (file) {
                       r.file = file;
                   }
                   const res: Message = toMessage(r);
                   replyToMessagesMap.set(r.hash, [res]);
              }
          }
      }
  }

  const childrenMessagesMap = new Map();
  if (hashes.length > 0) {
      const placeholders = hashes.map(() => '?').join(',');
      const childResults = await db.executeSql(
          `SELECT * FROM roomsmessages WHERE reply IN (${placeholders}) ORDER BY timestamp ASC`,
          hashes
      );
      
      for (const result of childResults) {
          for (let index = 0; index < result.rows.length; index++) {
              const r = result.rows.item(index);
              if (r !== undefined) {
                  const res: Message = toMessage(r);
                  if (!childrenMessagesMap.has(r.reply)) {
                      childrenMessagesMap.set(r.reply, []);
                  }
                  childrenMessagesMap.get(r.reply).push(res);
              }
          }
      }
  }

  for (const res of baseMessages) {
      res.replyto = replyToMessagesMap.get(res.reply) || [];
      const file = files.find((a: FileInfo) => a.hash === res.hash);

      if (file) {
        res.file = file;
      }
      
      if (
        res.replyto.length &&
        containsOnlyEmojis(res.message) &&
        res.message.length < 9
      ) {
        continue;
      }

      const replies = childrenMessagesMap.get(res.hash) || [];
      const reactions = addEmoji(replies);
      res.replies = [];
      res.reactions = reactions;
      const r: Message = toMessage(res);
      messages.push(r);
  }
  
  return messages.reverse();
}

export function addEmoji(replies: Message[]) {
  const reactions = [];
  for (const m of replies) {
    if (containsOnlyEmojis(m.message) && m.message.length < 9) {
      reactions.push({ emoji: m.message, sender: m.address });
    }
  }
  return reactions;
}

